assert.equal(await panel.evaluate(p=>!!p.previousElementSibling?.querySelector('input[name="package"][value="elements"]')),true);
const names=await panel.locator('.inline-element b').allTextContents();
assert.deepEqual(names,['Сиденья','Потолок','Пол / ковролин','Багажник','Дверные карты','Панель + консоль','Весь внутренний пластик','Текстильные коврики','Ремни безопасности','Стёкла внутри','Детское кресло']);
