import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,locale:'nb-NO',reducedMotion:'reduce'});
const page=await context.newPage();page.setDefaultTimeout(8000);
const cors={'Access-Control-Allow-Origin':'http://127.0.0.1:4173','Access-Control-Allow-Headers':'authorization, x-client-info, apikey, content-type','Access-Control-Allow-Methods':'GET, POST, OPTIONS'};
const fulfill=async r=>{if(r.request().method()==='OPTIONS')return r.fulfill({status:204,headers:cors,body:''});return r.fulfill({status:200,contentType:'application/json',headers:cors,body:'[]'})};
await page.route(/\/rest\/v1\/price_rules/,fulfill);await page.route(/\/rest\/v1\/app_settings/,fulfill);
await page.goto('http://127.0.0.1:4173/index.html',{waitUntil:'domcontentloaded'});
await page.locator('[data-lang="ru"]').click();
await page.locator('.service-card[data-service="car"] .service-head').click();
await page.waitForSelector('.service-card.open .step-title');
const next=async()=>{await page.locator('.service-card.open #next').click();await page.waitForTimeout(100)};
const material=page.locator('select[data-vehicle-material]');
await material.waitFor();
const materials=await material.locator('option').allTextContents();
assert.ok(materials.includes('Ткань'));
assert.ok(materials.includes('Алькантара'));
assert.ok(materials.includes('Натуральная кожа'));
assert.ok(materials.includes('Искусственная кожа / экокожа'));
assert.ok(materials.includes('Комбинированный салон'));
assert.ok(materials.includes('Не знаю / не уверен'));
await material.selectOption('leather');
assert.equal(await page.locator('input[name="vehicle_material"]').inputValue(),'leather');
await page.locator('input[name="seats"][value="5"]').check();
await next();
await page.locator('input[name="package"][value="elements"]').check();
await next();
await page.locator('input[name="condition"][value="medium"]').check();
await next();
await page.waitForFunction(()=>document.querySelector('.service-card.open .step-title')?.textContent.trim()==='Выберите элементы');
const seat=page.locator('input[name="el_seat"]');const ceiling=page.locator('input[name="el_ceiling"]');
await page.locator('label[for="el_seat"]').click();assert.equal(await seat.isChecked(),true);
const seatQty=page.locator('.element-qty[data-for="el_seat"]');await seatQty.waitFor();assert.equal(await seatQty.evaluate(e=>e.classList.contains('visible')),true);
const visibleQty=seatQty.locator('.qty-stepper input');assert.equal(await visibleQty.inputValue(),'1');
await seatQty.locator('[data-q="plus"]').click();await seatQty.locator('[data-q="plus"]').click();assert.equal(await visibleQty.inputValue(),'3');
assert.equal(await page.locator('input[name="seat_qty"]').inputValue(),'3');
await page.locator('label[for="el_ceiling"]').click();assert.equal(await ceiling.isChecked(),true);
assert.equal(await page.locator('label[for="el_seat"] .element-checkmark').textContent(),'✓');
assert.equal(await page.locator('label[for="el_ceiling"] .element-checkmark').textContent(),'✓');
await next();
await page.waitForFunction(()=>document.querySelector('.service-card.open .step-title')?.textContent.trim()==='Что ещё заметно?');
await context.close();await browser.close();console.log('MATERIAL + ELEMENTS UI REGRESSION PASS');
