await page.route(/\/rest\/v1\/app_settings/,async r=>{if(r.request().method()==='OPTIONS')return r.fulfill({status:204,headers:cors,body:''});return r.fulfill({status:200,contentType:'application/json',headers:cors,body:'[]'});});
