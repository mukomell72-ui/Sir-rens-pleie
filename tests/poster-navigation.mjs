import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true,locale:'nb-NO'});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route(/\/rest\/v1\//,r=>r.fulfill({status:200,contentType:'application/json',body:'[]'}));
const load=async()=>{
  await page.goto('http://127.0.0.1:4173/index.html',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('main')).display==='none');
};
await load();
assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('sir-poster-active')),true);
assert.equal(await page.locator('.sir-poster-frame>img').getAttribute('src'),'assets/sir-home-poster.webp');
assert.equal(await page.locator('.sir-poster-frame').evaluate(e=>Math.round(e.getBoundingClientRect().width)),390);
assert.equal(await page.locator('.sir-poster-frame').evaluate(e=>Math.round(e.getBoundingClientRect().height)),844);
assert.equal(await page.locator('.sir-poster').evaluate(e=>Math.round(e.getBoundingClientRect().height)),844);
assert.equal(await page.locator('.sir-poster-hint').isVisible(),false);
assert.equal(await page.locator('.service-card').first().isVisible(),false);
for(const service of ['car','sofa','chair','mattress'])assert.equal(await page.locator(`[data-poster-service="${service}"]`).count(),1);
assert.equal(await page.locator('[data-poster-service="car"]').getAttribute('data-tap-label'),'TRYKK');
assert.notEqual(await page.locator('[data-poster-service="car"]').evaluate(e=>getComputedStyle(e,'::after').animationName),'none');
await page.locator('[data-poster-service="car"]').click();
await page.waitForSelector('.service-card[data-service="car"].open');
assert.equal(await page.locator('.service-card[data-service="car"]').isVisible(),true);
assert.equal(await page.locator('body').evaluate(e=>e.classList.contains('sir-poster-active')),true);
assert.equal(await page.locator('.sir-poster-drawer').evaluate(e=>e.classList.contains('open')),true);
assert.equal(await page.locator('main').isVisible(),false);
await page.waitForTimeout(350);
assert.equal(await page.locator('.sir-drawer-content').evaluate(e=>e.scrollTop),0);
const barBottom=await page.locator('.sir-drawer-bar').evaluate(e=>e.getBoundingClientRect().bottom);
const cardTop=await page.locator('.sir-drawer-content>.service-card').evaluate(e=>e.getBoundingClientRect().top);
assert.ok(cardTop>=barBottom,`service card starts under drawer bar: ${cardTop} >= ${barBottom}`);
const actionsPosition=await page.locator('.sir-drawer-content .wizard-actions').evaluate(e=>getComputedStyle(e).position);
assert.equal(actionsPosition,'static');
const firstField=page.locator('.sir-drawer-content #step input').first();
const actions=page.locator('.sir-drawer-content .wizard-actions');
const fieldBox=await firstField.boundingBox();
const actionsBox=await actions.boundingBox();
assert.ok(!fieldBox||!actionsBox||fieldBox.y+fieldBox.height<=actionsBox.y,'navigation controls must not cover a form field');
await load();
await page.locator('[data-poster-lang="ru"]').click();
assert.equal(await page.locator('[data-lang="ru"]').evaluate(e=>e.classList.contains('active')),true);
assert.equal(await page.locator('[data-poster-service="car"]').getAttribute('data-tap-label'),'НАЖАТЬ');
await load();
await page.locator('[data-poster-need="odor"]').click();
await page.waitForSelector('.sir-profile [data-value="odor"].selected');
await load();
await page.locator('[data-poster-menu]').click();
assert.equal(await page.locator('[data-menu-service="rug"]').isVisible(),true);
assert.deepEqual(errors,[]);
await browser.close();console.log('POSTER NAVIGATION PASS');
