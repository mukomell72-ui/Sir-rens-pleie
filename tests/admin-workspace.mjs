import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,locale:'ru-RU'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));

await page.goto('http://127.0.0.1:4173/admin/',{waitUntil:'commit'});
await page.waitForSelector('#recoveryButton',{timeout:45000});
await page.locator('#recoveryButton').click();
assert.match(await page.locator('#loginStatus').innerText(),/Сначала введите email/);
await page.locator('#previewBtn').click();
await page.waitForSelector('#app:not(.hidden)');
assert.equal((await page.locator('#main h1').first().textContent()).trim(),'Сегодня');
assert.equal(await page.getByText('Только то, что требует решения или действия').count(),1);
assert.equal(await page.locator('[data-view="orders"]').count(),1);
assert.equal(await page.locator('[data-view="guide"]').count(),1);
const siteLink=await page.evaluate(()=>{const el=document.querySelector('.admin-site-link');return el&&{text:el.textContent.trim(),href:el.getAttribute('href'),target:el.target,rel:el.rel,visible:el.getClientRects().length>0}});
assert.deepEqual(siteLink,{text:'Открыть сайт',href:'../',target:'_blank',rel:'noopener noreferrer',visible:true});

await page.locator('[data-view="orders"]').click();
await page.waitForSelector('#orderSearch');
assert.equal(await page.locator('#orderStatus').count(),1);
assert.equal(await page.locator('.order-row').count(),3);
await page.locator('.order-row').first().click();
await page.waitForSelector('#demoOrderForm');
await page.waitForSelector('#inspectionWorkspace');
assert.match(await page.locator('#main').innerText(),/5 сидений, ремни безопасности/);
assert.match(await page.locator('#main').innerText(),/Повторный проход/);
assert.match(await page.locator('#inspectionWorkspace').innerText(),/Осмотр на месте/);
assert.match(await page.locator('#inspectionWorkspace').innerText(),/Химия и дозировка/);
await page.locator('#inspectionForm input[name="score"]').fill('9');
await page.locator('#inspectionForm input[name="minutes"]').fill('390');
await page.locator('#recalcAssessment').click();
assert.equal(await page.locator('#inspectionForm input[name="price"]').inputValue(),'4200');
await page.locator('#inspectionForm').locator('button[type="submit"]').click();
assert.match(await page.locator('#inspectionStatus').innerText(),/готова к согласованию/);
await page.locator('#demoOrderForm select[name="status"]').selectOption('scheduled');
await page.locator('#demoOrderForm input[name="price"]').fill('2600');
await page.locator('#demoOrderForm').locator('button[type="submit"]').click();
assert.match(await page.locator('#demoSaveStatus').innerText(),/Сохранено/);
await page.locator('#backOrders').click();
assert.equal(await page.locator('.order-row').count(),3);

await page.locator('.nav-more summary').click();
await page.locator('[data-view="finance"]').click();
await page.waitForSelector('.demo-purchases');
assert.equal(await page.locator('.demo-purchases tbody tr').count(),3);

await page.locator('[data-view="guide"]').click();
await page.waitForSelector('.guide-rules');
assert.equal(await page.locator('.guide-frame').count(),1);
assert.match(await page.locator('.guide-frame').getAttribute('src'),/guide-app\/index-v13\.html\?embedded=admin/);
const guideFrame=page.frameLocator('.guide-frame');
await guideFrame.locator('#q').waitFor();
assert.match(await guideFrame.locator('.sub').innerText(),/по названию или поверхности/);
assert.ok(await guideFrame.locator('.card').count()>20);
assert.ok(await guideFrame.locator('.thumb img').count()>=12);
await guideFrame.locator('.thumb img').first().waitFor();
assert.ok(await guideFrame.locator('.thumb img').first().evaluate(img=>img.complete&&img.naturalWidth>0));
await guideFrame.locator('#q').fill('Pol Star');
assert.ok(await guideFrame.locator('.card').count()>=1);
assert.match(await guideFrame.locator('.card').first().innerText(),/Pol Star/i);
await guideFrame.locator('#q').fill('пластик');
assert.ok(await guideFrame.locator('.card').count()>=2);
assert.match(await guideFrame.locator('#count').innerText(),/пластик/);
assert.ok((await guideFrame.locator('.card .mini').allInnerTexts()).every(text=>text.trim().length>10));
await guideFrame.locator('#q').fill('несуществующее-средство');
assert.equal(await guideFrame.locator('.card').count(),0);
assert.match(await guideFrame.locator('.empty-search').innerText(),/Ничего не найдено/);
await guideFrame.locator('#q').fill('');
assert.equal(await page.locator('.guide-frame').getAttribute('scrolling'),'no');
await page.waitForFunction(()=>document.querySelector('.guide-frame')?.getBoundingClientRect().height>3000);
assert.match(await page.locator('.guide-rules').innerText(),/spot-test либо STOP/);

const layout=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,viewport:innerWidth,top:document.querySelector('.admin-top').getBoundingClientRect(),main:document.querySelector('.main').getBoundingClientRect()}));
assert.ok(layout.doc<=layout.viewport+1,`Admin overflows mobile viewport: ${JSON.stringify(layout)}`);
assert.ok(layout.main.width<=layout.viewport+1);
assert.deepEqual(errors,[]);

await context.close();await browser.close();
console.log('ADMIN MOBILE WORKSPACE PASS');
