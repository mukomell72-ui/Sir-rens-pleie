await page.locator('[data-view="inventory"]').click();
await page.waitForSelector('.inventory-table');
assert.equal(await page.locator('.inventory-table tbody tr').count(),3);
assert.match(await page.locator('#main').innerText(),/Заканчивается/);

assert.equal(await page.locator('[data-view="finance"]').count(),0);
assert.equal(await page.getByText('Финансы / ENK',{exact:true}).count(),1);

await page.locator('[data-view="guide"]').click();
await page.waitForSelector('.guide-rules');
assert.equal(await page.locator('.guide-frame').count(),1);
assert.match(await page.locator('.guide-frame').getAttribute('src'),/guide-app\/index-v13\.html\?embedded=admin/);
const guideFrame=page.frameLocator('.guide-frame');
await guideFrame.locator('#q').waitFor();
assert.match(await guideFrame.locator('.sub').innerText(),/по названию или поверхности/);
assert.ok(await guideFrame.locator('.card').count()>20);
assert.ok(await guideFrame.locator('.thumb img').count()>=12);
await guideFrame.locator('.thumb img').first().waitFor();
