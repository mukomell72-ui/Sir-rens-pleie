assert.ok(await guideFrame.locator('.card').count()>=2);
assert.match(await guideFrame.locator('#count').innerText(),/пластик/i);
assert.ok((await guideFrame.locator('.card .mini').allInnerTexts()).every(text=>text.trim().length>10));
await guideFrame.locator('#q').fill('несуществующее-средство');
assert.equal(await guideFrame.locator('.card').count(),0);
assert.match(await guideFrame.locator('.empty-search').innerText(),/Ничего не найдено/);
await guideFrame.locator('#q').fill('');
assert.equal(await page.locator('.guide-frame').getAttribute('scrolling'),'no');
await page.waitForFunction(()=>document.querySelector('.guide-frame')?.getBoundingClientRect().height>3000);
assert.match(await page.locator('.guide-rules').innerText(),/spot-test либо STOP/);

const layout=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,viewport:innerWidth,top:document.querySelector('.admin-top').getBoundingClientRect(),main:document.querySelector('.main').getBoundingClientRect()}));
assert.ok(layout.doc<=layout.viewport+1,`Admin overflows mobile viewport: ${JSON.stringify(layout)}`);
assert.ok(layout.main.width<=layout.viewport+1);
assert.deepEqual(errors,[]);

await context.close();await browser.close();
console.log('ADMIN MOBILE WORKSPACE PASS');
