const translateHref=await page.locator('#openExternalTranslate').getAttribute('href');
assert.match(translateHref,/^https:\/\/translate\.google\.com\//);
const translateUrl=new URL(translateHref);
assert.match(translateUrl.searchParams.get('text')||'',/Машина уже готова/);
assert.equal(translateUrl.searchParams.get('tl'),'no');
