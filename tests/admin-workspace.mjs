const customSmsHref=await page.locator('[data-sms-custom]').getAttribute('href');
assert.match(customSmsHref,/^sms:/);
assert.match(decodeURIComponent(customSmsHref),/Bilen er klar/);

await page.locator('#inspectionForm input[name="score"]').fill('9');
await page.locator('#inspectionForm input[name="minutes"]').fill('390');
await page.locator('#recalcAssessment').click();
assert.equal(await page.locator('#inspectionForm input[name="price"]').inputValue(),'4200');
await page.locator('#inspectionForm').locator('button[type="submit"]').click();
assert.match(await page.locator('#inspectionStatus').innerText(),/готова к согласованию/);
await page.locator('#demoOrderForm select[name="status"]').selectOption('scheduled');
await page.locator('#demoOrderForm input[name="price"]').fill('2600');
await page.locator('#demoOrderForm').locator('button[type="submit"]').click();
assert.match(await page.locator('#demoSaveStatus').innerText(),/Сохранено/);
await page.locator('#backOrders').click();
assert.equal(await page.locator('.order-row').count(),3);
await page.locator('.order-row').nth(2).click();
await page.waitForSelector('.client-communication');
assert.equal(await page.locator('[data-sms-review]').count(),1);
